"""Clinical proposal and doctor approval workflow data models."""

from datetime import datetime
from enum import Enum
from typing import List, Optional
from pydantic import BaseModel, Field


class ProposalUrgency(str, Enum):
    """Urgency tier for physician notification."""
    ROUTINE = "ROUTINE"    # Within 4-12 hours
    URGENT = "URGENT"      # Within 30-60 minutes
    STAT = "STAT"          # Immediate bedside review (< 15 minutes)


class ActionState(str, Enum):
    """State machine status for human-in-the-loop review."""
    PENDING_REVIEW = "PENDING_REVIEW"
    APPROVED = "APPROVED"
    MODIFIED = "MODIFIED"
    DISMISSED = "DISMISSED"
    ESCALATED = "ESCALATED"


class ProposedIntervention(BaseModel):
    """Specific non-prescriptive recommendation presented for physician review."""
    intervention_type: str = Field(
        ...,
        description="Type: 'BEDSIDE_EVALUATION', 'REPEAT_LAB', 'OXYGEN_TITRATION', 'MEDICATION_REVIEW', etc."
    )
    description: str = Field(..., description="Actionable recommendation text for doctor review")
    rationale: str = Field(..., description="Clinical reasoning linking recommendation to underlying evidence")


class ClinicalProposal(BaseModel):
    """Synthesized clinical risk proposal generated by the multi-agent coordinator."""
    proposal_id: str = Field(..., description="Unique proposal identifier (e.g., 'PROP-2026-001')")
    patient_id: str = Field(..., description="Associated patient ID")
    generated_at: datetime = Field(default_factory=datetime.now, description="Timestamp of generation")
    composite_risk_score: float = Field(..., description="Deterministic aggregate risk score (e.g. NEWS2 total)")
    scoring_system: str = Field(..., description="Reference standard, e.g. 'NEWS2', 'qSOFA', 'KDIGO'")
    primary_concern: str = Field(..., description="Synthesis of primary clinical deterioration pattern")
    contributing_agent_findings: List[str] = Field(
        default_factory=list,
        description="List of finding_ids supporting this proposal"
    )
    recommended_actions: List[ProposedIntervention] = Field(
        ...,
        min_length=1,
        description="List of proposed interventions for physician sign-off"
    )
    urgency: ProposalUrgency = Field(default=ProposalUrgency.ROUTINE, description="Triage urgency tier")
    status: ActionState = Field(default=ActionState.PENDING_REVIEW, description="Human review status")


class DoctorAction(BaseModel):
    """Formal sign-off, modification, or rejection record by the reviewing physician."""
    action_id: str = Field(..., description="Unique sign-off action ID")
    proposal_id: str = Field(..., description="ID of the reviewed clinical proposal")
    patient_id: str = Field(..., description="Patient ID")
    action: ActionState = Field(..., description="Doctor's decision: APPROVED, MODIFIED, DISMISSED, ESCALATED")
    physician_id: str = Field(..., description="Attending/Resident ID (e.g. 'MD-4091')")
    physician_name: str = Field(..., description="Doctor's legal or professional name")
    reviewed_at: datetime = Field(default_factory=datetime.now, description="Timestamp of doctor action")
    clinical_notes: Optional[str] = Field(
        default=None,
        description="Physician's documented rationale, modifications, or overriding clinical observations"
    )
    modified_actions: Optional[List[str]] = Field(
        default=None,
        description="Updated interventions if action was MODIFIED"
    )
